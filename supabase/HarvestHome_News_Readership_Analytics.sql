-- HarvestHome News Readership Analytics
-- Run in Supabase SQL Editor. Additive only; existing marketplace tables and payment flows are untouched.
 
create schema if not exists private;

create table if not exists private.news_article_view_events (
  id bigint generated by default as identity primary key,
  article_id uuid not null references public.news_articles(id) on delete cascade,
  visitor_id uuid not null,
  session_id uuid not null,
  viewed_at timestamptz not null default now(),
  constraint news_article_view_events_article_session_key unique (article_id, session_id)
);
create index if not exists news_article_view_events_article_viewed_idx on private.news_article_view_events(article_id, viewed_at desc);
create index if not exists news_article_view_events_visitor_idx on private.news_article_view_events(visitor_id, viewed_at desc);
alter table private.news_article_view_events enable row level security;
revoke all on table private.news_article_view_events from public, anon, authenticated;

create or replace function public.record_news_article_view(p_slug text,p_visitor_id uuid,p_session_id uuid)
returns boolean language plpgsql security definer set search_path = '' as $function$
declare v_article_id uuid;
begin
 if p_slug is null or length(trim(p_slug))=0 or length(p_slug)>180 or p_visitor_id is null or p_session_id is null then return false; end if;
 if auth.uid() is not null and private.is_active_newsroom_staff() then return false; end if;
 select a.id into v_article_id from public.news_articles a where a.slug=trim(p_slug) and a.status='published' limit 1;
 if v_article_id is null then return false; end if;
 insert into private.news_article_view_events(article_id,visitor_id,session_id) values(v_article_id,p_visitor_id,p_session_id)
 on conflict (article_id,session_id) do nothing;
 return found;
end; $function$;
revoke all on function public.record_news_article_view(text,uuid,uuid) from public;
grant execute on function public.record_news_article_view(text,uuid,uuid) to anon,authenticated;

create or replace function public.get_news_article_view_stats()
returns jsonb language plpgsql security definer set search_path = '' as $function$
declare v_result jsonb;
begin
 if auth.uid() is null or not private.is_newsroom_admin() then raise exception 'Only HarvestHome Admins may view newsroom readership statistics'; end if;
 with article_stats as (
  select a.id article_id,a.title,a.slug,count(e.id)::bigint views,count(distinct e.visitor_id)::bigint unique_readers,max(e.viewed_at) last_viewed_at
  from public.news_articles a left join private.news_article_view_events e on e.article_id=a.id
  where a.status='published' group by a.id,a.title,a.slug
 )
 select jsonb_build_object(
  'total_views',coalesce((select sum(s.views) from article_stats s),0),
  'unique_readers',coalesce((select count(distinct e.visitor_id) from private.news_article_view_events e join public.news_articles a on a.id=e.article_id where a.status='published'),0),
  'articles',coalesce((select jsonb_agg(jsonb_build_object('article_id',s.article_id,'title',s.title,'slug',s.slug,'views',s.views,'unique_readers',s.unique_readers,'last_viewed_at',s.last_viewed_at) order by s.views desc,s.title) from article_stats s),'[]'::jsonb)
 ) into v_result;
 return v_result;
end; $function$;
revoke all on function public.get_news_article_view_stats() from public,anon;
grant execute on function public.get_news_article_view_stats() to authenticated;
